function rect(x:number,y:number,w:number,h:number,fill:string,stroke="#e2e8f0",r=10) {
  return '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="' + h + '" rx="' + r + '" fill="' + fill + '" stroke="' + stroke + '"/>';
}
function logoData(args:ClassicArgs) {
  if(!args.logoBytes?.length) return "";
  const mime = args.logoMime?.includes("svg")?"image/svg+xml":args.logoMime || "image/png";
  return 'data:' + mime + ';base64,' + Buffer.from(args.logoBytes).toString("base64");
}
