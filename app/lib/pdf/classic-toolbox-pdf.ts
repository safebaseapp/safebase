export async function generateClassicToolboxPdf(args: ClassicArgs): Promise<Uint8Array> {
  const rec=getToolboxBySlug(args.slug);
  if(!rec) throw new Error("Toolbox not found: "+args.slug);
  const data=rec[args.locale] as Content;
  const n=toolboxData.findIndex(x=>x.slug===args.slug)+1;
  const code="SRN-TBT-"+String(n).padStart(3,"0");
  const rev=args.documentProfile?.revision?.trim()||"00";
  const pages=[first(args,data,code,rev),second(args,data,code,rev),third(args,data,code,rev),fourth(args,data,code,rev)];
  const pdf=await PDFDocument.create();
  for(const svg of pages) {
    const paths=await outlineToolboxSvgText(svg);
    // 2x SVG raster density improves A4 print resolution while keeping the existing 72 masters untouched.
    const image=await sharp(Buffer.from(paths), { density: 144 }).png().toBuffer();
    const png=await pdf.embedPng(image);
    const page=pdf.addPage([PDF_W,PDF_H]);
    page.drawImage(png,{x:0,y:0,width:PDF_W,height:PDF_H});
  }
  pdf.setTitle(str(data.title));
  pdf.setSubject("SERNEM classic four-page HSE Toolbox Talk");
  pdf.setCreator("SERNEM HSE Document System");
  return pdf.save();
}
