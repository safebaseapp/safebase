import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PDFDocument, rgb } from "pdf-lib";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const downloadsDir = path.resolve(__dirname, "../public/downloads");

const WHITE = rgb(1, 1, 1);

async function cleanBrandedPdf(filePath) {
  const source = await readFile(filePath);
  const pdf = await PDFDocument.load(source);
  const pages = pdf.getPages();

  for (const page of pages) {
    const { width, height } = page.getSize();

    // Branded master header: remove company/project/document-control metadata
    // (company, project, document no, revision, date / issue date) while
    // preserving the reserved company-logo area and toolbox title.
    page.drawRectangle({
      x: width - 205,
      y: height - 68,
      width: 190,
      height: 58,
      color: WHITE,
      borderWidth: 0,
    });

    // Branded master footer: remove the repeated document no / revision.
    // Keep "Generated by SERNEM" on the left and page numbering on the right.
    page.drawRectangle({
      x: width / 2 - 90,
      y: 13,
      width: 180,
      height: 20,
      color: WHITE,
      borderWidth: 0,
    });
  }

  const cleaned = await pdf.save();
  await writeFile(filePath, cleaned);
}

async function main() {
  const entries = await readdir(downloadsDir, { withFileTypes: true });
  const brandedBaseFiles = entries
    .filter(
      (entry) =>
        entry.isFile() && entry.name.endsWith("-branded-base.pdf"),
    )
    .map((entry) => entry.name)
    .sort();

  if (brandedBaseFiles.length === 0) {
    console.log("[toolbox-pdf] No branded-base PDFs found; nothing to clean.");
    return;
  }

  for (const fileName of brandedBaseFiles) {
    await cleanBrandedPdf(path.join(downloadsDir, fileName));
  }

  console.log(
    `[toolbox-pdf] Cleaned branded header/footer metadata in ${brandedBaseFiles.length} PDFs.`,
  );
}

main().catch((error) => {
  console.error("[toolbox-pdf] Branded PDF cleanup failed:", error);
  process.exitCode = 1;
});
