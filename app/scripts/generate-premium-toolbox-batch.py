def _doc_control_block(c, meta, x_right, y_top, on_dark):
    """Sağ üstte doküman kontrol mini-tablosu."""
    label_col = MUTE if not on_dark else HexColor("#93C5FD")
    value_col = DARK if not on_dark else white
    rows = [
        (meta["l_docno"], meta["docno"]),
        (meta["l_rev"], meta["rev"]),
        (meta["l_date"], meta["issue"]),
    ]
    y = y_top
    for label, value in rows:
        _right(c, label, x_right - 40 * mm, y, 7, BOLD, label_col)
        _right(c, value, x_right, y, 7.5, REGULAR, value_col)
        y -= 4.6 * mm


def _header(c, meta, first_page):
    variant = meta["variant"]
    if variant == "standard":
        # Koyu kurumsal bant
        c.setFillColor(NAVY)
        c.rect(0, PAGE_H - HEADER_H, PAGE_W, HEADER_H, fill=1, stroke=0)
        # yeşil aksан çizgi
        c.setFillColor(GREEN)
        c.rect(0, PAGE_H - HEADER_H, PAGE_W, 1.6 * mm, fill=1, stroke=0)

        _shield(c, MARGIN + 5 * mm, PAGE_H - 8 * mm, 9 * mm)
        wm_x = MARGIN + 12 * mm
        _text(c, "SERNEM", wm_x, PAGE_H - 13.6 * mm, 15, BOLD, white)
        hse_x = wm_x + c.stringWidth("SERNEM", BOLD, 15) + 4
        _text(c, "HSE", hse_x, PAGE_H - 13.6 * mm, 15, BOLD, GREEN)
        _text(c, meta["kicker"], MARGIN + 12 * mm, PAGE_H - 18.8 * mm,
              7.5, BOLD, HexColor("#93C5FD"))

        _text(c, meta["title"], MARGIN, PAGE_H - 29 * mm, 17, BOLD, white)
        _text(c, meta["subtitle"], MARGIN, PAGE_H - 35 * mm, 8.5, REGULAR,
              HexColor("#CBD5E1"))

        _doc_control_block(c, meta, PAGE_W - MARGIN, PAGE_H - 10 * mm,
                           on_dark=True)
    else:
        # BRANDED-BASE: açık header, şirket kimliği ön planda
        c.setFillColor(CARD)
        c.rect(0, PAGE_H - HEADER_H, PAGE_W, HEADER_H, fill=1, stroke=0)
        # ince mavi aksan alt çizgi
        c.setFillColor(BLUE)
        c.rect(0, PAGE_H - HEADER_H, PAGE_W, 1.4 * mm, fill=1, stroke=0)

        # Rezerve logo alanı (route.ts logoyu buraya basar) — boş bırakılır.
        # Sağ üst: doküman kontrol
        _doc_control_block(c, meta, PAGE_W - MARGIN, PAGE_H - 8 * mm,
                           on_dark=False)

        # Başlık bloğu (logonun altında)
        _text(c, meta["kicker"], MARGIN, PAGE_H - 30.5 * mm, 7.5, BOLD, BLUE)
        _text(c, meta["title"], MARGIN, PAGE_H - 37 * mm, 15, BOLD, NAVY)

    # ipucu: alt içerik başlangıç y'si
    return PAGE_H - HEADER_H - 9 * mm


def _footer(c, meta, page_no):
    y = FOOTER_H
    c.setStrokeColor(BORDER)
    c.setLineWidth(0.6)
    c.line(MARGIN, y, PAGE_W - MARGIN, y)

    if meta["variant"] == "standard":
        _text(c, meta["footer_left"], MARGIN, y - 5.5 * mm, 7, REGULAR, MUTE)
    else:
        # Küçük ve zarif "Generated by SERNEM"
        _text(c, meta["gen_by"], MARGIN, y - 5.5 * mm, 7, REGULAR, MUTE)

    _text(c, f"{meta['docno']} · Rev {meta['rev']}",
          PAGE_W / 2.0 - 26 * mm, y - 5.5 * mm, 7, REGULAR, MUTE)
    _right(c, meta["page_lbl"].format(n=page_no), PAGE_W - MARGIN, y - 5.5 * mm,
           7, BOLD, SLATE)


