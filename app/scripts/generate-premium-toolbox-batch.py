def _checklist(doc, items):
    """İki sütunlu onay kutucuklu saha checklist'i."""
    c = doc.c
    col_w = (CONTENT_W - 8 * mm) / 2.0
    col_x = [MARGIN, MARGIN + col_w + 8 * mm]
    # her satır tek satıra sığacak şekilde tasarlandı
    row_h = 8.6 * mm
    rows = (len(items) + 1) // 2
    block_h = rows * row_h + 3 * mm
    doc.need(block_h)
    for i, item in enumerate(items):
        col = i % 2
        row = i // 2
        x = col_x[col]
        y = doc.y - row * row_h
        c.setStrokeColor(BLUE)
        c.setLineWidth(1.0)
        c.rect(x, y - 3.6 * mm, 3.6 * mm, 3.6 * mm, fill=0, stroke=1)
        for line in _wrap(c, item, col_w - 7 * mm, 8.6, REGULAR)[:1]:
            _text(c, line, x + 6 * mm, y - 3.2 * mm, 8.6, REGULAR, DARK)
    doc.y -= block_h


def _standards(doc, items):
    """Compact 2x2 reference cards that translate standards into field action."""
    c = doc.c
    gap = 4 * mm
    card_w = (CONTENT_W - gap) / 2
    prepared = []
    for item in items:
        body = _wrap(c, item["body"], card_w - 11 * mm, 7.4, REGULAR)
        prepared.append((item["code"], item["title"], body))

    row_heights = []
    for row in range(2):
        row_items = prepared[row * 2:row * 2 + 2]
        max_lines = max(len(item[2]) for item in row_items)
        row_heights.append(14 * mm + max_lines * 3.8 * mm)

    total_h = sum(row_heights) + gap
    doc.need(total_h + 2 * mm)
    top = doc.y
    accents = [BLUE, GREEN, AMBER, SLATE]
    fills = [PALE_BLUE, PALE_GREEN, PALE_AMBER, PALE_SLATE]

    idx = 0
    for row, card_h in enumerate(row_heights):
        row_top = top - sum(row_heights[:row]) - row * gap
        for col in range(2):
            code, title, body_lines = prepared[idx]
            x = MARGIN + col * (card_w + gap)
            accent = accents[idx]
            c.setFillColor(fills[idx])
            c.setStrokeColor(BORDER)
            c.setLineWidth(.55)
            c.roundRect(x, row_top - card_h, card_w, card_h, 2.2 * mm,
                        fill=1, stroke=1)
            c.setFillColor(accent)
            c.roundRect(x, row_top - card_h, 2.5 * mm, card_h, 1.1 * mm,
                        fill=1, stroke=0)
            _text(c, code, x + 6 * mm, row_top - 6 * mm, 7, BOLD, accent)
            _text(c, title, x + 6 * mm, row_top - 10.5 * mm, 8.2, BOLD, NAVY)
            ty = row_top - 15 * mm
            for line in body_lines:
                _text(c, line, x + 6 * mm, ty, 7.4, REGULAR, SLATE)
                ty -= 3.8 * mm
            idx += 1
    doc.y = top - total_h - 3 * mm


def _attendance(doc, meta):
    c = doc.c
    fields = meta["att_fields"]
    headers = meta["att_headers"]
    rows = 12
    # Generous handwritten sign-off rows on the dedicated approval sheet.
    row_h = 11.5 * mm
    # üst bilgi alanı (2x2) + tablo başlığı + satırlar
    info_h = 18 * mm
    table_h = 8 * mm + rows * row_h
    total = info_h + table_h + 4 * mm
    doc.need(total)
    y = doc.y

    # bilgi alanı kutucukları
    fw = (CONTENT_W - 6 * mm) / 2.0
    positions = [
        (MARGIN, y - 6 * mm),
        (MARGIN + fw + 6 * mm, y - 6 * mm),
        (MARGIN, y - 15.5 * mm),
        (MARGIN + fw + 6 * mm, y - 15.5 * mm),
    ]
    for (label, (fx, fy)) in zip(fields, positions):
        _text(c, label + ":", fx, fy, 8, BOLD, SLATE)
        c.setStrokeColor(BORDER)
        c.setLineWidth(0.6)
        lx = fx + c.stringWidth(label + ": ", BOLD, 8) + 2 * mm
        c.line(lx, fy - 0.6 * mm, fx + fw, fy - 0.6 * mm)
    y -= info_h

    # tablo başlığı
    col_w = [12 * mm, 62 * mm, CONTENT_W - 12 * mm - 62 * mm - 36 * mm, 36 * mm]
    xs = [MARGIN]
    for w in col_w:
        xs.append(xs[-1] + w)
    c.setFillColor(NAVY)
    c.rect(MARGIN, y - 8 * mm, CONTENT_W, 8 * mm, fill=1, stroke=0)
    for i, htext in enumerate(headers):
        _text(c, htext, xs[i] + 2.5 * mm, y - 5.4 * mm, 8, BOLD, white)
    ry = y - 8 * mm
    c.setStrokeColor(BORDER)
    c.setLineWidth(0.6)
    for r in range(rows):
        top = ry - r * row_h
        if r % 2 == 1:
            c.setFillColor(PALE_SLATE)
            c.rect(MARGIN, top - row_h, CONTENT_W, row_h, fill=1, stroke=0)
        c.setStrokeColor(BORDER)
        c.rect(MARGIN, top - row_h, CONTENT_W, row_h, fill=0, stroke=1)
        for xi in xs[1:-1]:
            c.line(xi, top - row_h, xi, top)
        _text(c, str(r + 1), xs[0] + 4 * mm, top - 5.4 * mm, 8, REGULAR, SLATE)
    doc.y = ry - rows * row_h - 4 * mm


