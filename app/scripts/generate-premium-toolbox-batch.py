def _text(c, s, x, y, size=9, font=REGULAR, color=DARK):
    c.setFillColor(color)
    c.setFont(font, size)
    c.drawString(x, y, s)


def _right(c, s, x, y, size=9, font=REGULAR, color=DARK):
    c.setFillColor(color)
    c.setFont(font, size)
    c.drawRightString(x, y, s)


def _wrap(c, value, width, size=9, font=REGULAR):
    if value is None:
        value = ""
    words = str(value).split()
    lines, cur = [], ""
    for w in words:
        cand = f"{cur} {w}".strip()
        if c.stringWidth(cand, font, size) <= width:
            cur = cand
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines or [""]


def _shield(c, cx, top, w, outer=NAVY_DEEP, inner=BLUE):
    """Küçük SERNEM kalkan amblemi (üst-orta noktası `top`, genişlik `w`)."""
    h = w * 1.02
    x0 = cx - w / 2.0
    y0 = top - h

    def poly(scale):
        sw = w * scale
        sh = h * scale
        ox = cx - sw / 2.0
        oy = top - (h - sh) / 2.0 - sh
        pts = [
            (ox + sw * 0.5, oy + sh * 1.00),
            (ox + sw * 1.00, oy + sh * 0.78),
            (ox + sw * 1.00, oy + sh * 0.36),
            (ox + sw * 0.5, oy + sh * 0.00),
            (ox + sw * 0.00, oy + sh * 0.36),
            (ox + sw * 0.00, oy + sh * 0.78),
        ]
        p = c.beginPath()
        p.moveTo(*pts[0])
        for pt in pts[1:]:
            p.lineTo(*pt)
        p.close()
        return p

    c.setFillColor(outer)
    c.drawPath(poly(1.0), fill=1, stroke=0)
    c.setFillColor(inner)
    c.drawPath(poly(0.80), fill=1, stroke=0)

    # beyaz onay işareti
    c.setStrokeColor(white)
    c.setLineWidth(w * 0.11)
    c.setLineCap(1)
    c.setLineJoin(1)
    p = c.beginPath()
    p.moveTo(x0 + w * 0.30, y0 + h * 0.52)
    p.lineTo(x0 + w * 0.45, y0 + h * 0.38)
    p.lineTo(x0 + w * 0.72, y0 + h * 0.66)
    c.drawPath(p, fill=0, stroke=1)


